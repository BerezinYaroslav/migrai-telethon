def cell(value: str | int) -> dict:
    if isinstance(value, int):
        return {"userEnteredValue": {"numberValue": value}}
    return {"userEnteredValue": {"stringValue": value}}


def main() -> None:
    scan = json.loads(SCAN.read_text(encoding="utf-8"))
    selected = []
    for chat in scan["chats"]:
        for match in chat["matches"]:
            key = (chat["sheet_row"], match["message_id"])
            if key not in LEADS:
                continue
            topic, summary, draft = LEADS[key]
            selected.append(
                {
                    **match,
                    "country": chat["country"],
                    "chat": chat["name"],
                    "sheet_row": chat["sheet_row"],
                    "topic": topic,
                    "summary": summary,
                    "draft": draft,
                    "manual_score": max(match["score"], 5),
                }
            )
    if len(selected) != len(LEADS):
        raise RuntimeError(f"Expected {len(LEADS)} selected messages, found {len(selected)}")
    if len({item["user_id"] for item in selected}) != len(selected):
        raise RuntimeError("Selected Telegram authors are not unique")

    SHORTLIST.write_text(json.dumps(selected, ensure_ascii=False, indent=2), encoding="utf-8")
    serial = (date(2026, 10, 13) - date(1899, 12, 30)).days
    rows = []
    profile_links = []
    signal_links = []
    for item in selected:
        username = item["username"]
        handle = f"@{username}" if username else str(item["user_id"])
        signal_date = item["message_date"][:10]
        comment = f"Сигнал от {signal_date}. {item['summary']}"
        if item["score"] < 5:
            comment += f" Ручная оценка: {item['manual_score']}; автоматический балл: {item['score']}."
        if signal_date < "2026-08-01":
            comment += " Проверить актуальность обращения."
        values = [
            handle,
            item["display_name"],
            "Новый",
            item["chat"],
            item["link"],
            item["excerpt"],
            item["draft"],
            item["topic"],
            item["manual_score"],
            item["country"],
            serial,
            "Не рассмотрен",
            comment,
        ]
        rows.append({"values": [cell(value) for value in values]})
        profile_links.append(
            {
                "values": [
                    {
                        "userEnteredFormat": {
                            "textFormat": {"link": {"uri": f"https://t.me/{username}"}}
                        }
                    }
                    if username
                    else {"userEnteredFormat": {"textFormat": {}}}
                ]
            }
        )
        signal_links.append(
            {
                "values": [
                    {
                        "userEnteredFormat": {
                            "textFormat": {"link": {"uri": item["link"]}}
                        }
                    }
                ]
            }
        )

    start_index = 66  # Google row 67
    end_index = start_index + len(rows)
    requests = [
        {
            "updateCells": {
                "range": {
                    "sheetId": SHEET_ID,
                    "startRowIndex": start_index,
                    "endRowIndex": end_index,
                    "startColumnIndex": 0,
                    "endColumnIndex": 13,
                },
                "rows": rows,
                "fields": "userEnteredValue",
            }
        },
        {
            "updateCells": {
                "range": {
                    "sheetId": SHEET_ID,
                    "startRowIndex": start_index,
                    "endRowIndex": end_index,
                    "startColumnIndex": 4,
                    "endColumnIndex": 5,
                },
                "rows": signal_links,
                "fields": "userEnteredFormat.textFormat.link",
            }
        },
        {
            "updateCells": {
                "range": {
                    "sheetId": SHEET_ID,
                    "startRowIndex": start_index,
                    "endRowIndex": end_index,
                    "startColumnIndex": 0,
                    "endColumnIndex": 1,
                },
                "rows": profile_links,
                "fields": "userEnteredFormat.textFormat.link",
            }
        },
    ]
    for request in requests:
        update = request["updateCells"]
        grid = update["range"]
        assert grid["endRowIndex"] - grid["startRowIndex"] == len(update["rows"])
        assert all(
            len(row["values"]) == grid["endColumnIndex"] - grid["startColumnIndex"]
            for row in update["rows"]
        )
    PAYLOAD.write_text(
        json.dumps({"spreadsheet_id": SPREADSHEET_ID, "requests": requests}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "selected": len(selected),
                "start_row": start_index + 1,
                "end_row": end_index,
                "requests": len(requests),
                "countries": sorted({item["country"] for item in selected}),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
